#!/usr/bin/env python
"""Mechanical validator for bench/readability/held_out.yaml.

Re-run by P3.06 (PR check) and P5.01 (taxonomy conformance).

Exit 0 on pass with one summary line.
Exit 1 on the first failure with a specific message naming the item and field.

Do not edit this file to make a failing item pass. Edit the item.
"""
import re
import sys

try:
    import yaml
except ImportError:
    sys.stderr.write("error: PyYAML not installed. Run: pip install pyyaml\n")
    sys.exit(1)

STUB = 'bench/readability/taxonomy_stub.yaml'
HELD = 'bench/readability/held_out.yaml'

HINT_STYLE = re.compile(r'\b(you should|try adjusting|check that your|make sure)\b',
                        re.IGNORECASE)
AMHARIC = re.compile(r'[\u1200-\u137F]')
PLACEHOLDER = {'correct', 'readable', 'appropriate', 'good', 'fine'}

REQUIRED_FIELDS = (
    'id', 'misconception_id', 'sim', 'grade_band', 'question_text',
    'expected_factual_correctness', 'expected_readability',
    'expected_uncertainty_framing',
)
EXPECTED_FIELDS = (
    'expected_factual_correctness', 'expected_readability',
    'expected_uncertainty_framing',
)
SIMS = ('mechanics', 'waves_optics', 'electricity')
ITEMS_PER_SIM = 20
ITEMS_PER_MID = 4


def fail(msg):
    print(f"FAIL: {msg}")
    sys.exit(1)


def load_yaml(path):
    try:
        with open(path, 'r', encoding='utf-8') as f:
            return yaml.safe_load(f)
    except FileNotFoundError:
        fail(f"{path} not found")
    except yaml.YAMLError as e:
        fail(f"{path} is not valid YAML: {e}")


stub = load_yaml(STUB)
if not isinstance(stub, dict) or 'sims' not in stub:
    fail(f"{STUB}: missing top-level 'sims' key")

stub_ids = set()
for sim, items in stub['sims'].items():
    if sim not in SIMS:
        fail(f"{STUB}: unknown sim {sim}")
    for it in items:
        if 'id' not in it:
            fail(f"{STUB}: item missing id in sim {sim}")
        stub_ids.add(it['id'])

data = load_yaml(HELD)
if not isinstance(data, list):
    fail(f"{HELD} is not a top-level YAML list (got {type(data).__name__})")
if len(data) != 60:
    fail(f"{HELD}: expected 60 items, got {len(data)}")

per_sim = {s: 0 for s in SIMS}
per_mid = {}
seen_ids = set()

for idx, it in enumerate(data):
    label = it.get('id', f'item[{idx}]') if isinstance(it, dict) else f'item[{idx}]'

    if not isinstance(it, dict):
        fail(f"{label}: not a YAML mapping")

    for k in REQUIRED_FIELDS:
        if k not in it:
            fail(f"{label}: missing field {k}")

    if it['id'] in seen_ids:
        fail(f"{label}: duplicate item id")
    seen_ids.add(it['id'])

    if it['sim'] not in SIMS:
        fail(f"{label}: unknown sim {it['sim']!r}")

    if it['misconception_id'] not in stub_ids:
        fail(f"{label}: misconception_id {it['misconception_id']!r} not in taxonomy stub")

    if not isinstance(it['question_text'], str) or not it['question_text'].rstrip().endswith('?'):
        fail(f"{label}: question_text does not end with '?'")

    if HINT_STYLE.search(it['question_text']):
        fail(f"{label}: question_text contains hint-style phrasing")

    if AMHARIC.search(it['question_text']):
        fail(f"{label}: question_text contains Amharic characters")

    for k in EXPECTED_FIELDS:
        val = it[k]
        if not isinstance(val, str):
            fail(f"{label}: {k} is not a string")
        if len(val.split()) < 8:
            fail(f"{label}: {k} is too short ({len(val.split())} words); specific assertion required")
        if val.strip().lower() in PLACEHOLDER:
            fail(f"{label}: {k} is a placeholder ({val.strip()!r}); specific assertion required")
        if AMHARIC.search(val):
            fail(f"{label}: {k} contains Amharic characters")

    per_sim[it['sim']] += 1
    per_mid[it['misconception_id']] = per_mid.get(it['misconception_id'], 0) + 1

for sim in SIMS:
    if per_sim[sim] != ITEMS_PER_SIM:
        fail(f"{sim}: expected {ITEMS_PER_SIM} items, got {per_sim[sim]}")

for mid, n in per_mid.items():
    if n != ITEMS_PER_MID:
        fail(f"{mid}: expected {ITEMS_PER_MID} items, got {n}")

for mid in stub_ids:
    if mid not in per_mid:
        fail(f"stub id {mid} has no held-out item")

print(f"held_out ok: {len(data)} items, {len(per_mid)} misconceptions, "
      f"mechanics={per_sim['mechanics']} "
      f"waves_optics={per_sim['waves_optics']} "
      f"electricity={per_sim['electricity']}")
